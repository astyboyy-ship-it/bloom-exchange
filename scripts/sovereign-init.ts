// Initializes a Sovereign node: generates its secrets, derives its Ed25519 root key and mints the node's own
// Operator access key. Everything is local; nothing leaves the machine.
//
//   npm run sovereign:init                       first run: creates deploy/.env, deploy/root-key.public.json, deploy/keys/operator.key
//   npm run sovereign:init -- --org "Acme Fund"  names the node (printed on the root key record and the operator key)
//   npm run sovereign:init -- --rotate           regenerates every secret (invalidates the old root key and operator key)
import { randomBytes, randomUUID } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { parseArgs } from "node:util";
import { deriveExchangeKeys } from "../packages/core/src/key-derivation.ts";
import { ROLE_DEFAULTS, ROLE_TIER, type UnsignedBloomPayload } from "../packages/core/src/licensing/types.ts";
import { issueAndSave } from "./key-common.ts";

const { values } = parseArgs({ options: { org: { type: "string" }, rotate: { type: "boolean", default: false }, dir: { type: "string", default: "deploy" } } });
const dir = values.dir!;
const envFile = join(dir, ".env");
const hex = () => randomBytes(32).toString("hex");

function readEnv(file: string): Record<string, string> {
  if (!existsSync(file)) return {};
  return Object.fromEntries(
    readFileSync(file, "utf8")
      .split(/\r?\n/)
      .filter((l) => /^[A-Z0-9_]+=/.test(l))
      .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1).replace(/^"|"$/g, "")]),
  );
}

const prior = values.rotate ? {} : readEnv(envFile);
const org = values.org ?? prior.BLOOM_NODE_ORG ?? "Sovereign Node";
const env: Record<string, string> = {
  BLOOM_NODE_ORG: org,
  BLOOM_EXCHANGE_SECRET: prior.BLOOM_EXCHANGE_SECRET ?? hex(),
  LICENSE_SIGNING_SECRET: prior.LICENSE_SIGNING_SECRET ?? hex(),
  SRH_TOKEN: prior.SRH_TOKEN ?? hex(),
  BLOOM_PORT: prior.BLOOM_PORT ?? "3000",
  BLOOM_BIND: prior.BLOOM_BIND ?? "127.0.0.1",
};
const created = !existsSync(envFile) || values.rotate;

mkdirSync(join(dir, "keys"), { recursive: true });
writeFileSync(
  envFile,
  ["# Bloom Exchange · Sovereign node. Generated by `npm run sovereign:init`. Keep this file secret and off git.", "# Rotating BLOOM_EXCHANGE_SECRET changes the node's root key; rotating LICENSE_SIGNING_SECRET invalidates issued access keys.", ...Object.entries(env).map(([k, v]) => `${k}=${v}`), ""].join("\n"),
  { encoding: "utf8", mode: 0o600 },
);

const root = deriveExchangeKeys(env.BLOOM_EXCHANGE_SECRET);
const record = {
  org,
  alg: "Ed25519",
  kid: root.kid,
  fingerprint: root.fingerprint,
  jwk: { kty: "OKP", crv: "Ed25519", x: root.publicX, kid: root.kid, alg: "EdDSA", use: "sig" },
  createdAt: new Date().toISOString(),
  note: "Public half only. Share it out of band so counterparties can verify this node's BLOOM-XCH certificates offline.",
};
writeFileSync(join(dir, "root-key.public.json"), `${JSON.stringify(record, null, 2)}\n`, "utf8");

process.env.LICENSE_SIGNING_SECRET = env.LICENSE_SIGNING_SECRET;
const base = ROLE_DEFAULTS.operator;
const payload: UnsignedBloomPayload = {
  keyId: `op_${randomUUID()}`,
  holderName: `${org} / Sovereign Operator`,
  role: "operator",
  tier: ROLE_TIER.operator,
  unlockedEngines: base.unlockedEngines,
  themeConfig: base.theme,
  permissions: base.permissions,
  issuedAt: new Date().toISOString(),
  expiresAt: null,
};
const issued = await issueAndSave(payload, join(dir, "keys", "operator.key"), { value: env.LICENSE_SIGNING_SECRET, dev: false });

const rel = (p: string) => relative(process.cwd(), p) || p;
console.log(`
  BLOOM EXCHANGE // SOVEREIGN NODE ${created ? "INITIALIZED" : "REFRESHED (existing secrets kept)"}

  org            ${org}
  root key       Ed25519 · ${root.kid}
  fingerprint    ${root.fingerprint}

  secrets        ${rel(envFile)}            (owner-only; never commit)
  public key     ${rel(join(dir, "root-key.public.json"))}
  operator key   ${rel(issued.path)}

  Next:
    npm run sovereign:up                               build and start the node (Docker Compose)
    open http://${env.BLOOM_BIND}:${env.BLOOM_PORT}    then "Have a Bloom key?" and paste the operator key
`);

// Initializes the Sovereign nodes in deploy/docker-compose.yml: for node-alpha and node-beta it generates
// separate secrets, derives each node's Ed25519 root key and mints each node's own Operator access key.
// Everything is local; nothing leaves the machine.
//
//   npm run sovereign:init                                         creates deploy/.env, deploy/<node>-root-key.public.json, deploy/keys/<node>-operator.key
//   npm run sovereign:init -- --alpha "Acme Fund" --beta "Northwind" names the nodes (printed on their key records and operator keys)
//   npm run sovereign:init -- --rotate                             regenerates every secret (invalidates old root keys and operator keys)
//
// For a single node (or Kubernetes, which runs one node per namespace), use the alpha values: BLOOM_EXCHANGE_SECRET =
// ALPHA_EXCHANGE_SECRET, LICENSE_SIGNING_SECRET = ALPHA_LICENSE_SECRET.
import { randomBytes, randomUUID } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { parseArgs } from "node:util";
import { deriveExchangeKeys } from "../packages/core/src/key-derivation.ts";
import { ROLE_DEFAULTS, ROLE_TIER, type UnsignedBloomPayload } from "../packages/core/src/licensing/types.ts";
import { issueAndSave } from "./key-common.ts";

const { values } = parseArgs({ options: { alpha: { type: "string" }, beta: { type: "string" }, rotate: { type: "boolean", default: false }, dir: { type: "string", default: "deploy" } } });
const dir = values.dir!;
const envFile = join(dir, ".env");
const hex = () => randomBytes(32).toString("hex");

function readEnv(file: string): Record<string, string> {
  if (!existsSync(file)) return {};
  return Object.fromEntries(
    readFileSync(file, "utf8")
      .split(/\r?\n/)
      .filter((l) => /^[A-Z0-9_]+=/.test(l))
      .map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1).replace(/^"|"$/g, "")]),
  );
}

const prior = values.rotate ? {} : readEnv(envFile);
const env: Record<string, string> = {
  ALPHA_ORG: values.alpha ?? prior.ALPHA_ORG ?? "Alpha",
  ALPHA_EXCHANGE_SECRET: prior.ALPHA_EXCHANGE_SECRET ?? hex(),
  ALPHA_LICENSE_SECRET: prior.ALPHA_LICENSE_SECRET ?? hex(),
  ALPHA_PORT: prior.ALPHA_PORT ?? "3001",
  BETA_ORG: values.beta ?? prior.BETA_ORG ?? "Beta",
  BETA_EXCHANGE_SECRET: prior.BETA_EXCHANGE_SECRET ?? hex(),
  BETA_LICENSE_SECRET: prior.BETA_LICENSE_SECRET ?? hex(),
  BETA_PORT: prior.BETA_PORT ?? "3002",
  SRH_TOKEN: prior.SRH_TOKEN ?? hex(),
  BLOOM_BIND: prior.BLOOM_BIND ?? "127.0.0.1",
};
const created = !existsSync(envFile) || values.rotate;

mkdirSync(join(dir, "keys"), { recursive: true });
writeFileSync(
  envFile,
  ["# Bloom Exchange · Sovereign nodes. Generated by `npm run sovereign:init`. Keep this file secret and off git.", "# Rotating an *_EXCHANGE_SECRET changes that node's root key; rotating an *_LICENSE_SECRET invalidates its issued access keys.", ...Object.entries(env).map(([k, v]) => `${k}=${v}`), ""].join("\n"),
  { encoding: "utf8", mode: 0o600 },
);

const rel = (p: string) => relative(process.cwd(), p) || p;
const lines: string[] = [];
for (const node of ["alpha", "beta"] as const) {
  const P = node.toUpperCase();
  const org = env[`${P}_ORG`];
  const root = deriveExchangeKeys(env[`${P}_EXCHANGE_SECRET`]);
  const record = {
    node: `node-${node}`,
    org,
    alg: "Ed25519",
    kid: root.kid,
    fingerprint: root.fingerprint,
    jwk: { kty: "OKP", crv: "Ed25519", x: root.publicX, kid: root.kid, alg: "EdDSA", use: "sig" },
    createdAt: new Date().toISOString(),
    note: "Public half only. Share it out of band so counterparties can verify this node's BLOOM-XCH certificates offline.",
  };
  const recordPath = join(dir, `${node}-root-key.public.json`);
  writeFileSync(recordPath, `${JSON.stringify(record, null, 2)}\n`, "utf8");

  // Each operator key is signed with its own node's license secret; the verifier reads it from the env.
  process.env.LICENSE_SIGNING_SECRET = env[`${P}_LICENSE_SECRET`];
  const base = ROLE_DEFAULTS.operator;
  const payload: UnsignedBloomPayload = {
    keyId: `op_${randomUUID()}`,
    holderName: `${org} / Sovereign Operator`,
    role: "operator",
    tier: ROLE_TIER.operator,
    unlockedEngines: base.unlockedEngines,
    themeConfig: base.theme,
    permissions: base.permissions,
    issuedAt: new Date().toISOString(),
    expiresAt: null,
  };
  const issued = await issueAndSave(payload, join(dir, "keys", `${node}-operator.key`), { value: env[`${P}_LICENSE_SECRET`], dev: false });
  lines.push(`  node-${node.padEnd(6)} ${org}`, `    root key     Ed25519 · ${root.kid}`, `    fingerprint  ${root.fingerprint}`, `    public key   ${rel(recordPath)}`, `    operator key ${rel(issued.path)}`, `    desk         http://${env.BLOOM_BIND}:${env[`${P}_PORT`]}`, "");
}

console.log(`
  BLOOM EXCHANGE // SOVEREIGN NODES ${created ? "INITIALIZED" : "REFRESHED (existing secrets kept)"}

${lines.join("\n")}  secrets          ${rel(envFile)}   (owner-only; never commit)

  Next:
    npm run sovereign:up       build and start both nodes (Docker Compose)
    npm run demo:two-node      watch them discover each other and settle a cross-node deal each way
`);

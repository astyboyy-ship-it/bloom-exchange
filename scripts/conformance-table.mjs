// Regenerates SPEC.md Appendix B (conformance vectors) from the test suite:
//   npm run spec:conformance
// Runs vitest with the JSON reporter, assigns each test a stable conformance id by suite and order, and rewrites
// the block between the BEGIN/END markers in SPEC.md.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";

const ROOT = join(import.meta.dirname, "..");
const AREAS = [
  ["packages/core/test/vectors.test.ts", "VEC", "§5, §9, App. A"],
  ["packages/core/test/e2e-settlement.test.ts", "SETTLE", "§4, §6, §9, §11"],
  ["packages/core/test/settlement-safety.test.ts", "CLAMP", "§8"],
  ["packages/core/test/x402-resource.test.ts", "X402", "§9"],
  ["packages/core/test/leakage.test.ts", "VAULT", "§7"],
  ["packages/core/test/firewall.test.ts", "SHIELD", "§10"],
  ["packages/core/test/resources.test.ts", "RES", "§8"],
  ["packages/core/test/omni.test.ts", "OMNI", "§6, §10"],
  ["packages/core/test/sovereign.test.ts", "NODE", "§3, §10"],
  ["packages/core/test/peers.test.ts", "PEER", "§3"],
  ["packages/core/test/router.test.ts", "HTTP", "§4"],
  ["packages/core/test/public-url.test.ts", "ORIGIN", "§3, §12 (non-normative)"],
  ["packages/sdk/test/cli.test.ts", "VERIFY", "§11"],
  ["packages/sdk/test/strip-types.test.ts", "BUILD", "non-normative"],
  ["packages/mcp/test/mcp.test.ts", "MCP", "§11 (non-normative)"],
  ["packages/core/test/events.test.ts", "EVT", "§7 (non-normative event feed)"],
  ["packages/core/test/events-scope.test.ts", "EVTSCOPE", "§7, §12 (non-normative event feed)"],
  ["packages/core/test/events-webhook.test.ts", "HOOK", "non-normative"],
  ["packages/mcp/test/events.test.ts", "MCPEVT", "non-normative"],
  ["apps/node/test/copy-parity.test.ts", "DESK", "non-normative"],
  ["packages/schemas/test/schemas.test.ts", "SCHEMA", "non-normative (relay, docs/RELAY_PROTOCOL.md)"],
  ["packages/sdk/test/relay.test.ts", "EDGE", "non-normative (relay, docs/RELAY_PROTOCOL.md)"],
  ["apps/relay/test/relay.test.ts", "RELAY", "non-normative (relay, docs/RELAY_PROTOCOL.md)"],
  ["apps/relay/test/postgres.test.ts", "RELAYPG", "non-normative (relay)"],
  ["apps/relay/test/serverless.test.ts", "RELAYSLS", "non-normative (relay on serverless)"],
  ["packages/mcp/test/network.test.ts", "MCPNET", "non-normative (relay)"],
  ["tests/phase2-e2e.test.ts", "RELAYE2E", "non-normative (relay, docs/RELAY_PROTOCOL.md)"],
  ["tests/seed-sellers.test.ts", "SEED", "non-normative (reference liquidity)"],
];

const out = join(mkdtempSync(join(tmpdir(), "bcp-")), "report.json");
try {
  execFileSync(process.execPath, [join(ROOT, "node_modules", "vitest", "vitest.mjs"), "run", "--reporter=json", `--outputFile=${out}`], { cwd: ROOT, stdio: "ignore" });
} catch {
  // A failing run still writes the report; failures show in the Status column.
}
const report = JSON.parse(readFileSync(out, "utf8"));
const byFile = new Map(report.testResults.map((r) => [r.name.replace(/\\/g, "/").replace(`${ROOT.replace(/\\/g, "/")}/`, ""), r.assertionResults]));

const rows = [];
let total = 0;
let passed = 0;
for (const [file, area, section] of AREAS) {
  const tests = byFile.get(file) ?? [];
  tests.forEach((t, i) => {
    total++;
    if (t.status === "passed") passed++;
    const name = [...t.ancestorTitles, t.title].join(" › ").replace(/\|/g, "\\|");
    rows.push(`| BCP-${area}-${String(i + 1).padStart(2, "0")} | ${section} | ${name} | \`${file.split("/").pop()}\` | ${t.status === "passed" ? "pass" : t.status} |`);
  });
}
const unmapped = [...byFile.keys()].filter((f) => !AREAS.some(([a]) => a === f));
if (unmapped.length) throw new Error(`test files without a conformance area: ${unmapped.join(", ")}`);

const block = [
  "<!-- BEGIN CONFORMANCE (generated by npm run spec:conformance; do not edit by hand) -->",
  `${total} vectors, ${passed} passing at generation time.`,
  "",
  "| ID | Spec | Vector | Suite | Status |",
  "|---|---|---|---|---|",
  ...rows,
  "<!-- END CONFORMANCE -->",
].join("\n");

const specPath = join(ROOT, "SPEC.md");
const spec = readFileSync(specPath, "utf8");
const next = spec.replace(/<!-- BEGIN CONFORMANCE[\s\S]*?<!-- END CONFORMANCE -->/, block);
if (next === spec && !spec.includes("<!-- BEGIN CONFORMANCE")) throw new Error("SPEC.md has no conformance markers");
writeFileSync(specPath, next);
console.log(`SPEC.md Appendix B: ${total} vectors (${passed} passing).`);
